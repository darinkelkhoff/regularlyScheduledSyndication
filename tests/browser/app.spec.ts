async function decodeFeedQr(page: Page) {
  const pixels = await page.getByRole('img', { name: 'Feed URL QR code', exact: true }).evaluate(async (image: HTMLImageElement) => {
    await image.decode();
    const canvas = document.createElement('canvas'); canvas.width = image.naturalWidth; canvas.height = image.naturalHeight;
    const context = canvas.getContext('2d')!; context.drawImage(image, 0, 0);
    return { data: Array.from(context.getImageData(0, 0, canvas.width, canvas.height).data), width: canvas.width, height: canvas.height };
  });
  return jsQR(new Uint8ClampedArray(pixels.data), pixels.width, pixels.height)?.data;
}
async function checkTypography(page: Page) {
  const undersized = await page.evaluate(() => {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT); const failures: string[] = [];
    while (walker.nextNode()) {
      const node = walker.currentNode; const element = node.parentElement;
      if (!node.textContent?.trim() || !element || ['STYLE', 'SCRIPT'].includes(element.tagName) || !element.getClientRects().length) continue;
      const style = getComputedStyle(element);
      if (style.visibility !== 'hidden' && parseFloat(style.fontSize) < 14) failures.push(`${node.textContent.trim().slice(0, 60)}: ${style.fontSize}`);
    }
    return failures;
  });
  expect(undersized).toEqual([]);

  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
}
