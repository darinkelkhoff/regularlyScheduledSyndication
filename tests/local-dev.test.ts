import { SourceVault } from '../src/security/source-vault.ts';
import { ImportService } from '../src/importer/service.ts';
import { Subscriptions } from '../src/db/subscriptions.ts';
import { LocalPublisher } from '../src/publishing/local-publisher.ts';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readdir, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { localDatabase } from '../scripts/local-database.ts';
test('local database migration tracking survives a restart without reapplying ALTER statements', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'regsched-dev-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const first = await localDatabase(directory);
  let active: typeof first | undefined = first;
  t.after(() => active?.runtime.dispose());
  await first.db.prepare('INSERT INTO users (id, display_name) VALUES (?, ?)').bind('local-user', 'Local').run();
  const vault = await SourceVault.create(new Uint8Array(32).fill(9));
  const xml = await readFile(new URL('./fixtures/podcast.xml', import.meta.url), 'utf8');
  const source = await new ImportService(first.db, vault, async () => ({ status: 200, xml })).preview('local-user', 'https://example.com/feed');
  const id = await new Subscriptions(first.db).create('local-user', source.sourceId, { schedule: { kind: 'daily', hour: 12, timeZone: 'UTC' }, selection: { mode: 'all' }, live: false, choice: 'next' }, new Date().toISOString());
  const largeXml = `<?xml version="1.0"?><rss version="2.0"><channel><title>Large feed</title><description>${'a'.repeat(3 * 1024 * 1024)}</description></channel></rss>`;
  const publisher = new LocalPublisher(first.db, vault, first.bucket, async () => largeXml);
  await publisher.publish('local-user', id);
  const token = (await publisher.token('local-user', id))!;
  const saved = await publisher.read(token);
  assert.equal(saved, largeXml);
  active = undefined;
  await first.runtime.dispose();
  const second = await localDatabase(directory);
  active = second;
  const restartedPublisher = new LocalPublisher(second.db, vault, second.bucket);
  assert.equal(await restartedPublisher.token('local-user', id), token);
  assert.equal(await restartedPublisher.read(token), saved);
  assert.equal((await second.db.prepare('SELECT display_name FROM users WHERE id = ?').bind('local-user').first())?.display_name, 'Local');
  assert.equal((await second.db.prepare('SELECT COUNT(*) AS n FROM local_migrations').first())?.n, (await readdir(new URL('../migrations/', import.meta.url))).filter(name => name.endsWith('.sql')).length);
});
