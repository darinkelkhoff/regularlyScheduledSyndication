test('URL preview and subscription creation use owned saved sources without returning private URLs', async t => {
  const xml = await readFile(new URL('./fixtures/podcast.xml', import.meta.url), 'utf8').then(xml => xml.replace('<channel>', '<channel><image><url>https://cdn.example/cover.jpg</url></image>'));
  const env: AppBindings = { LOCAL_PREVIEW: '1', DB: await database(t), ORIGIN: 'http://localhost:8787', RP_ID: 'localhost', RP_NAME: 'RegSched', SOURCE_SECRET: Buffer.alloc(32, 7).toString('base64url'), FEED_TRANSPORT: async () => ({ status: 200, xml }) };
  env.FEED_PUBLISHER = new LocalPublisher(env.DB, await SourceVault.create(new Uint8Array(32).fill(7)), new MemoryFeedStore());
  const auth = new AuthService(env.DB, { origin: env.ORIGIN, rpID: env.RP_ID, rpName: env.RP_NAME });
  const options = await auth.signupOptions('Importer', 'browser');
  const user = await auth.register(options.challengeId, new Authenticator().register(options.options.challenge), 'browser');
  const request = (path: string, body?: unknown) => app.request(env.ORIGIN + path, { method: body === undefined ? 'GET' : 'POST', headers: { Origin: env.ORIGIN, 'Content-Type': 'application/json', Cookie: `regsched_session=${user.token}` }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }, env);
  const preview = await request('/sources/preview', {});
  assert.equal(preview.status, 404);
  const sourceResponse = await request('/api/sources/preview', { url: 'https://member:secret@podcast.example/feed?token=private' });
  assert.equal(sourceResponse.status, 200);
  const source = await sourceResponse.json() as { sourceId: string; title: string; artworkUrl: string | null };
  assert.equal(source.artworkUrl, 'https://cdn.example/cover.jpg');
  assert.equal(source.title, 'Signal Paths'); assert.ok(!JSON.stringify(source).includes('token=private'));
  const created = await request('/api/podcasts', { sourceId: source.sourceId, schedule: { kind: 'daily', hour: 12, timeZone: 'UTC' }, selection: { mode: 'all' }, live: true, choice: 'now' });
  assert.equal(created.status, 201); const { id } = await created.json() as { id: string };
  assert.equal((await request(`/api/podcasts/${id}/refresh`, {})).status, 200);
  const detail = await (await request('/api/podcasts/' + id)).json() as { state: { releases: unknown[] }; live: boolean; lastSuccessAt: string; artworkUrl: string };
  assert.equal(detail.artworkUrl, source.artworkUrl);
  const library = await (await request('/api/podcasts')).json() as { podcasts: { artworkUrl: string; timeZone: string; nextEpisode: { title: string } | null }[] };
  assert.equal(library.podcasts[0]!.artworkUrl, source.artworkUrl);
  assert.equal(library.podcasts[0]!.timeZone, 'UTC');
  assert.equal(library.podcasts[0]!.nextEpisode?.title, 'The second connection');
  assert.equal(detail.live, true); assert.equal(detail.state.releases.length, 1); assert.ok(detail.lastSuccessAt);
  const feedResponse = await request(`/api/podcasts/${id}/rss-preview`);
  assert.equal(feedResponse.status, 200);
  assert.match(feedResponse.headers.get('Content-Type')!, /application\/rss\+xml/);
  assert.equal(feedResponse.headers.get('Cache-Control'), 'no-store');
  const xmlPreview = await feedResponse.text();
  assert.ok(xmlPreview.includes('The first connection'));
  assert.ok(!xmlPreview.includes('The second connection'));
  assert.ok(xmlPreview.includes('https://audio.example/one.mp3'));
  assert.ok(xmlPreview.includes('https://cdn.example/cover.jpg'));
  assert.equal(await (await request(`/api/podcasts/${id}/rss-preview`)).text(), xmlPreview);
  const otherOptions = await auth.signupOptions('Other listener', 'other-browser');
  const other = await auth.register(otherOptions.challengeId, new Authenticator().register(otherOptions.options.challenge), 'other-browser');
  assert.equal((await app.request(env.ORIGIN + `/api/podcasts/${id}/rss-preview`, { headers: { Cookie: `regsched_session=${other.token}` } }, env)).status, 404);
  assert.equal((await request('/api/podcasts/' + id)).status, 200);
  env.LOCAL_PREVIEW = undefined;
  assert.equal((await request(`/api/podcasts/${id}/rss-preview`)).status, 404);
  env.LOCAL_PREVIEW = '1';
  const feed = await (await request(`/api/podcasts/${id}/feed`, { action: 'reveal' })).json() as { url: string };
  const delivered = await app.request(feed.url, {}, env);
  assert.equal(delivered.status, 200);
  assert.equal(delivered.headers.get('Cache-Control'), 'no-store');
  assert.match(delivered.headers.get('Content-Type')!, /application\/rss\+xml/);
  assert.ok(delivered.headers.get('X-Robots-Tag')!.includes('noindex'));
  const feedXml = await delivered.text(); assert.ok(feedXml.includes('The first connection'));
  assert.equal((await app.request(env.ORIGIN + `/api/podcasts/${id}/feed`, { method: 'POST', headers: { Origin: env.ORIGIN, 'Content-Type': 'application/json', Cookie: `regsched_session=${other.token}` }, body: JSON.stringify({ action: 'reset' }) }, env)).status, 404);
  const reset = await (await request(`/api/podcasts/${id}/feed`, { action: 'reset' })).json() as { url: string };
  assert.notEqual(reset.url, feed.url);
  assert.equal((await app.request(feed.url, {}, env)).status, 404);
  assert.equal(await (await app.request(reset.url, {}, env)).text(), feedXml);
  const revealed = await request('/api/podcasts/' + id + '/source-url', {});
  assert.equal((await revealed.json() as { url: string }).url, 'https://member:secret@podcast.example/feed?token=private');
  const duplicate = await request('/api/podcasts', { sourceId: source.sourceId, schedule: { kind: 'daily', hour: 12, timeZone: 'UTC' }, selection: { mode: 'all' }, live: false, choice: 'next' });
  assert.equal(duplicate.status, 409);
  const deletionRevision = (await (await request('/api/podcasts/' + id)).json() as { revision: number }).revision;
  assert.equal((await app.request(env.ORIGIN + `/api/podcasts/${id}/delete`, { method: 'POST', headers: { Origin: env.ORIGIN, 'Content-Type': 'application/json', Cookie: `regsched_session=${other.token}` }, body: JSON.stringify({ revision: deletionRevision }) }, env)).status, 404);
  assert.equal((await request(`/api/podcasts/${id}/delete`, { revision: deletionRevision - 1 })).status, 409);
  assert.equal((await request(`/api/podcasts/${id}/delete`, { revision: deletionRevision })).status, 200);
  assert.equal((await request('/api/podcasts/' + id)).status, 404);
  assert.equal((await app.request(reset.url, {}, env)).status, 404);
  const reimport = await request('/api/sources/preview', { url: 'https://member:secret@podcast.example/feed?token=private' });
  assert.equal(reimport.status, 200);
  assert.notEqual((await reimport.json() as { sourceId: string }).sourceId, source.sourceId);

});
test('saves a chosen selection containing 2000 imported episode identities', async t => {
  const xml = `<rss version="2.0"><channel><title>Large archive</title>${Array.from({ length: 2000 }, (_, i) => `<item><guid>large-${i}</guid><title>Episode ${i}</title><enclosure url="https://audio.example/${i}.mp3" type="audio/mpeg" length="10"/></item>`).join('')}</channel></rss>`;
  const env: AppBindings = { DB: await database(t), ORIGIN: 'http://localhost:8787', RP_ID: 'localhost', RP_NAME: 'RegSched', SOURCE_SECRET: Buffer.alloc(32, 7).toString('base64url'), FEED_TRANSPORT: async () => ({ status: 200, xml }) };
  const auth = new AuthService(env.DB, { origin: env.ORIGIN, rpID: env.RP_ID, rpName: env.RP_NAME });
  const options = await auth.signupOptions('Archive listener', 'browser');
  const user = await auth.register(options.challengeId, new Authenticator().register(options.options.challenge), 'browser');
  const request = (path: string, body: unknown) => app.request(env.ORIGIN + path, { method: 'POST', headers: { Origin: env.ORIGIN, 'Content-Type': 'application/json', Cookie: `regsched_session=${user.token}` }, body: JSON.stringify(body) }, env);
  const response = await request('/api/sources/preview', { url: 'https://podcast.example/archive' });
  assert.equal(response.status, 200);
  const source = await response.json() as { sourceId: string; episodes: { id: string }[] };
  assert.equal(source.episodes.length, 2000);
  const created = await request('/api/podcasts', { sourceId: source.sourceId, schedule: { kind: 'daily', hour: 12, timeZone: 'UTC' }, selection: { mode: 'choose', ids: source.episodes.map(episode => episode.id) }, live: false, choice: 'next' });
  assert.equal(created.status, 201);
});
